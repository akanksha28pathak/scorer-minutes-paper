"""Run-to-run noise table for the scorer-minutes paper (idea 1), from docs/TASK_MATRIX.md.

  python3 analysis/noise_table.py [--matrix docs/TASK_MATRIX.md] [--extra-csv more_runs.csv]
                                  [--out results/paper/noise_long.csv] [--markdown results/paper/noise_table.md]

Reads the per-task tables of the generated task matrix (one column per finished full run, cells ✅ / ❌), maps each run
column to its config (the run tag without the split and pass suffix: g31_v12d_train55_p2 -> g31_v12d), writes a long
CSV (config, split, run, task, solved; task ids and 0/1 only, no task content) and prints the noise report of
tools/scorer_minutes (per-config SD, pooled SD per split, task-level SD, P(wrong order), runs needed).
--extra-csv adds runs not in the matrix as summary rows (config,split,run,solved,n), e.g. runs from DECISIONS_31B.md.
--pool-exclude CONFIG... keeps configs out of the noise report (they stay in the long CSV): use it for configs whose
repeats ran on different hardware (g31_v12e: A100 vs converted RTX PRO 6000), so that the pooled "identical-run" SD
is independent of the conversion it is used to judge (Gemini review G0, Nov 6).
Regenerate the matrix first (analysis/make_task_matrix.py) so every finished run is included. CPU only, stdlib only.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "scorer_minutes" / "src"))
from scorer_minutes.noise import Table, from_rows, read_csv, report_markdown  # noqa: E402

CELL = {"✅": 1, "❌": 0}


def config_of(run: str, split: str) -> str:
    m = re.match(rf"^(.*?)_{re.escape(split)}(?:_.*)?$", run)
    return m.group(1) if m else run


def parse_matrix(path: Path) -> list[dict]:
    rows, split, header = [], None, None
    for line in path.read_text(encoding="utf-8").splitlines():
        h = re.match(r"^## (\w+)\b", line)
        if h:
            split, header = h.group(1), None
            continue
        if not line.startswith("| ") or split is None:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0] == "Task":
            header = cells
            continue
        if header is None or cells[0].startswith(("*", "-")) or set(cells[0]) <= {"-"}:
            continue
        if len(cells) != len(header) or not all(c in CELL for c in cells[2:]):
            continue
        for run, c in zip(header[2:], cells[2:]):
            rows.append({"config": config_of(run, split), "split": split, "run": run, "task": cells[0],
                         "solved": CELL[c]})
    return rows


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--matrix", default=str(ROOT / "docs" / "TASK_MATRIX.md"))
    ap.add_argument("--extra-csv", nargs="*", default=[])
    ap.add_argument("--pool-exclude", nargs="*", default=[], help="configs left out of the noise report")
    ap.add_argument("--out", default=str(ROOT / "results" / "paper" / "noise_long.csv"))
    ap.add_argument("--markdown", default=str(ROOT / "results" / "paper" / "noise_table.md"))
    a = ap.parse_args()
    rows = parse_matrix(Path(a.matrix))
    if not rows:
        sys.exit(f"no per-task run tables found in {a.matrix}")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["config", "split", "run", "task", "solved"])
        w.writeheader()
        w.writerows(rows)
    table = Table([r for r in from_rows(rows).runs + (read_csv(a.extra_csv).runs if a.extra_csv else [])
                   if r.config not in a.pool_exclude])
    md = (f"# Run-to-run noise (generated by analysis/noise_table.py from {Path(a.matrix).name}"
          f"{' + ' + ', '.join(Path(p).name for p in a.extra_csv) if a.extra_csv else ''}"
          f"{'; excluded: ' + ', '.join(a.pool_exclude) if a.pool_exclude else ''})\n\n" + report_markdown(table))
    Path(a.markdown).parent.mkdir(parents=True, exist_ok=True)
    Path(a.markdown).write_text(md, encoding="utf-8")
    print(md)
    print(f"long CSV: {a.out} ({len(rows)} rows); report: {a.markdown}", file=sys.stderr)


if __name__ == "__main__":
    main()
